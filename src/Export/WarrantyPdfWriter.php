<?php
declare(strict_types=1);

namespace GlpiPlugin\Warrantycolors\Export;

use Glpi\Search\Output\Tcpdf;
use PhpOffice\PhpSpreadsheet\Cell\Coordinate;
use PhpOffice\PhpSpreadsheet\Spreadsheet;
use RuntimeException;

/**
 * PDF writer based on GLPI's native TCPDF implementation.
 *
 * Preserves explicit column widths, while keeping GLPI's
 * PDF footer, metadata and table styling.
 */
final class WarrantyPdfWriter extends Tcpdf
{
    public static function configureColumns(
        Spreadsheet $workbook,
        array $columns
    ): bool {
        $count = count($columns);

        // Optional layout helper limited to manageable A4 tables.
        if ($count < 2 || $count > 12) {
            return false;
        }

        $nameIndex = null;
        $warrantyIndex = null;

        foreach ($columns as $index => $column) {
            if (($column['itemtype'] ?? null) !== 'Computer') {
                continue;
            }

            $id = (int) ($column['id'] ?? -1);

            if ($id === 1) {
                $nameIndex = $index + 1;
            } elseif ($id === 120) {
                $warrantyIndex = $index + 1;
            }
        }

        if ($nameIndex === null || $warrantyIndex === null) {
            return false;
        }

        $sheet = $workbook->getActiveSheet();

        // Default width for secondary columns.
        for ($index = 1; $index <= $count; $index++) {
            $letter = Coordinate::stringFromColumnIndex($index);

            $dimension = $sheet->getColumnDimension($letter);
            $dimension->setAutoSize(false);
            $dimension->setWidth(7.5);
        }

        // Give computer names enough room to remain readable.
        $nameColumn = Coordinate::stringFromColumnIndex(
            $nameIndex
        );

        $sheet->getColumnDimension($nameColumn)
            ->setWidth(30);

        // Preserve readable warranty dates and labels.
        $warrantyColumn = Coordinate::stringFromColumnIndex(
            $warrantyIndex
        );

        $sheet->getColumnDimension($warrantyColumn)
            ->setWidth(18);

        return true;
    }

    /**
     * Preserve the cell widths generated by PhpSpreadsheet.
     *
     * GLPI normally removes these widths. The change is scoped
     * to this writer and does not affect native GLPI exports.
     */
    public static function preserveWidths(string $html): string
    {
        $result = preg_replace(
            [
                '|</style>|',
                '|padding-left:\d+px;|',
            ],
            [
                'table { width: 100%; };</style>',
                '',
            ],
            $html
        );

        if ($result === null) {
            throw new RuntimeException(
                'Unable to prepare PDF HTML'
            );
        }

        return $result;
    }

    protected function createExternalWriterInstance(
        $orientation,
        $unit,
        $paperSize
    ): \TCPDF {
        $pdf = parent::createExternalWriterInstance(
            $orientation,
            $unit,
            $paperSize
        );

        $this->setEditHtmlCallback(
            [self::class, 'preserveWidths']
        );

        return $pdf;
    }
}
