<?php
declare(strict_types=1);

namespace GlpiPlugin\Warrantycolors\Controller;

use Computer;
use DateTimeImmutable;
use Glpi\Controller\AbstractController;
use Glpi\Search\Output\Pdf;
use Glpi\Search\Output\Xlsx;
use Glpi\Search\Output\Ods;
use Glpi\Search\Output\Csv;
use Glpi\Search\SearchEngine;
use Glpi\Search\Provider\SQLProvider;
use GlpiPlugin\Warrantycolors\Export\WarrantyNativeExportOutput;
use GlpiPlugin\Warrantycolors\Export\WarrantyExportLimit;
use RuntimeException;
use Search;
use Symfony\Component\HttpFoundation\Request;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\HttpKernel\Exception\AccessDeniedHttpException;
use Symfony\Component\Routing\Attribute\Route;

/**
 * Warranty Colors exports using the authenticated GLPI search engine.
 *
 * Full exports are guarded by a 1,000-result limit.
 */
final class ExportPreviewController extends AbstractController
{
    private const MAX_ALL_EXPORT_ROWS = 1000;

    #[Route(
        '/ExportPreview',
        name: 'warrantycolors_export_preview',
        methods: ['GET']
    )]
    public function __invoke(Request $request): Response
    {
        if (!Computer::canView()) {
            throw new AccessDeniedHttpException();
        }

        // Same parameter manager used by GLPI's native export.
        $searchInput = $request->query->all();

        $scope = $searchInput['scope'] ?? 'page';

        if (!is_string($scope) || !in_array(
            $scope,
            ['page', 'all'],
            true
        )) {
            throw new \Symfony\Component\HttpKernel\Exception\BadRequestHttpException(
                'Unsupported export scope'
            );
        }

        // These parameters control our endpoint, not GLPI's search.
        // Prevent caller-supplied values from overriding export limits.
        unset(
            $searchInput['scope'],
            $searchInput['format'],
            $searchInput['export_all'],
            $searchInput['list_limit'],
            $searchInput['display_type']
        );

        $params = Search::manageParams(
            Computer::class,
            $searchInput
        );

        // Safety limits for the first integration test.
        $format = $request->query->get('format', 'pdf');

        if (!is_string($format) || !in_array(
            $format,
            ['pdf', 'xlsx', 'ods', 'csv'],
            true
        )) {
            throw new \Symfony\Component\HttpKernel\Exception\BadRequestHttpException(
                'Unsupported export format'
            );
        }

        $params['display_type'] = match ($format) {
            'pdf'  => Search::PDF_OUTPUT_LANDSCAPE,
            'xlsx' => Search::XLSX_OUTPUT,
            'ods'  => Search::ODS_OUTPUT,
            'csv'  => Search::CSV_OUTPUT,
        };
        // Use GLPI's native page size and current page offset.
        // For a complete export, GLPI removes the SQL LIMIT.
        $params['export_all'] = ($scope === 'all') ? 1 : 0;

        if ($scope === 'all') {
            $params['start'] = 0;
        }
        $params['as_map'] = 0;

        // Check the result count before building a complete export.
        // Keep the same search criteria and GLPI access restrictions.
        if ($scope === 'all') {
            $countParams = $params;
            $countParams['export_all'] = 0;
            $countParams['start'] = 0;
            $countParams['list_limit'] = 1;

            // Prepare the same authorized search as GLPI.
            $countData = SearchEngine::prepareDataForSearch(
                Computer::class,
                $countParams
            );

            SQLProvider::constructSQL($countData);

            $countSql = $countData['sql']['search'] ?? null;

            if (!is_string($countSql) || trim($countSql) === '') {
                throw new RuntimeException(
                    'Unable to prepare export count query'
                );
            }

            // An unfiltered search already has a SQL LIMIT and
            // an independent COUNT query generated by GLPI.
            // Filtered searches may have no SQL LIMIT at all.
            if (!($countData['search']['no_search'] ?? false)) {
                $countSql = rtrim($countSql);

                if (preg_match(
                    '/\\bLIMIT\\s+\\d+(?:\\s*,\\s*\\d+)?\\s*$/i',
                    $countSql
                )) {
                    throw new RuntimeException(
                        'Unexpected pre-existing search limit'
                    );
                }

                $countData['sql']['search'] = $countSql
                    . ' LIMIT '
                    . (self::MAX_ALL_EXPORT_ROWS + 1);
            }

            // Count only: do not build GLPI result rows.
            SQLProvider::constructData($countData, true);

            $totalCount = $countData['data']['totalcount'] ?? null;

            WarrantyExportLimit::assertAllowed(
                $totalCount,
                self::MAX_ALL_EXPORT_ROWS
            );
        }

        // Full PDF exports require additional TCPDF memory.
        // Never lower an existing limit or override unlimited memory.
        if ($scope === 'all' && $format === 'pdf') {
            $currentLimit = ini_get('memory_limit');

            if ($currentLimit === false) {
                throw new RuntimeException(
                    'Unable to read PHP memory limit'
                );
            }

            $targetBytes = 256 * 1024 * 1024;
            $currentBytes = ini_parse_quantity($currentLimit);

            if ($currentBytes !== -1 && $currentBytes < $targetBytes) {
                $previousLimit = ini_set('memory_limit', '256M');
                $effectiveLimit = ini_get('memory_limit');

                if ($previousLimit === false
                    || $effectiveLimit === false
                    || ini_parse_quantity($effectiveLimit) < $targetBytes) {
                    throw new \Symfony\Component\HttpKernel\Exception\ServiceUnavailableHttpException(
                        null,
                        'PDF export requires at least 256 MiB PHP memory'
                    );
                }
            }
        }

        // SearchEngine applies GLPI rights and entity restrictions.
        $data = SearchEngine::getData(
            Computer::class,
            $params
        );

        $columns = $data['data']['cols'] ?? [];

        $hasWarranty = false;

        foreach ($columns as $column) {
            if (
                ($column['itemtype'] ?? null) === 'Computer'
                && (int) ($column['id'] ?? -1) === 120
            ) {
                $hasWarranty = true;
                break;
            }
        }

        if (!$hasWarranty) {
            throw new RuntimeException(
                'Warranty search option 120 is not displayed'
            );
        }

        $native = match ($format) {
            'pdf'  => new Pdf(Pdf::LANDSCAPE),
            'xlsx' => new Xlsx(),
            'ods'  => new Ods(),
            'csv'  => new Csv(),
        };

        $output = new WarrantyNativeExportOutput(
            $native,
            new DateTimeImmutable('today')
        );

        // Capture the output generated by the native GLPI writer.
        $bufferLevel = ob_get_level();
        ob_start();

        try {
            $output->displayData($data, $params);
            $bytes = ob_get_clean();
        } catch (\Throwable $error) {
            while (ob_get_level() > $bufferLevel) {
                ob_end_clean();
            }
            throw $error;
        }

        if (!is_string($bytes) || strlen($bytes) < 10) {
            throw new RuntimeException('Empty export');
        }

        if ($format === 'pdf'
            && !str_starts_with($bytes, '%PDF-')) {
            throw new RuntimeException('Invalid PDF');
        }

        if (in_array($format, ['xlsx', 'ods'], true)
            && !str_starts_with($bytes, "PK\x03\x04")) {
            throw new RuntimeException('Invalid spreadsheet');
        }

        // Native GLPI already emitted download headers.
        // Symfony owns the final HTTP response.
        header_remove('Content-Disposition');
        header_remove('Content-Type');

        $mime = match ($format) {
            'pdf' => 'application/pdf',
            'xlsx' => 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
            'ods' => 'application/vnd.oasis.opendocument.spreadsheet',
            'csv' => 'text/csv; charset=UTF-8',
        };

        return new Response($bytes, 200, [
            'Content-Type' => $mime,
            'Content-Disposition' =>
                'attachment; filename="warrantycolors-preview.' . $format . '"',
            'Cache-Control' => 'private, no-store',
        ]);
    }
}
